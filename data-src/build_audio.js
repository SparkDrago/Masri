#!/usr/bin/env node
/* Course audio = recordings of a real Egyptian speaker (made in the site's studio, /#record).

     node data-src/build_audio.js --add masri-recordings-2026-11-21.zip [more.zip …]
         unpacks studio ZIPs into audio/: trims silence, evens out loudness and converts to MP3
         (with ffmpeg, if installed; otherwise the files are copied as they are), keeps the
         originals in recordings-original/ (not deployed), then updates the manifest.
     node data-src/build_audio.js            how much of the course is recorded (also: --status)
     node data-src/build_audio.js --missing  list every sentence that has no recording yet
     node data-src/build_audio.js --manifest rebuild js/data/audio-manifest.js from audio/

   Synthesized voices are off by default (js/config.js). The old generators still work:
     --export   audio/jobs.tsv for data-src/namaa_tts.py      --azure   generate with Azure
     --voices f,m   which voices to count / generate (default: both for status, f otherwise) */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const AUDIO = path.join(ROOT, 'audio');
const args = process.argv.slice(2);
const flag = (n) => args.includes('--' + n);
const opt = (n, d) => { const i = args.indexOf('--' + n); return i >= 0 && args[i + 1] ? args[i + 1] : d; };

// Accepted audio files: <id>.mp3 (listed as the bare id), or .m4a / .webm / .ogg / .wav (listed with the extension).
// When several exist for one id, a recording (.m4a/.webm/.ogg) wins over generated .mp3/.wav.
function writeManifest() {
  const RANK = { m4a: 0, webm: 1, ogg: 2, mp3: 3, wav: 4 };
  const best = new Map();
  (fs.existsSync(AUDIO) ? fs.readdirSync(AUDIO) : []).forEach((f) => {
    const m = f.match(/^([0-9a-f]{16})\.(mp3|m4a|webm|ogg|wav)$/);
    if (m && (!best.has(m[1]) || RANK[m[2]] < RANK[best.get(m[1])])) best.set(m[1], m[2]);
  });
  const list = [...best].sort().map(([id, ext]) => (ext === 'mp3' ? id : id + '.' + ext));
  fs.writeFileSync(path.join(ROOT, 'js/data/audio-manifest.js'),
    `/* Generated by data-src/build_audio.js — ids of the files in /audio (voice|text hash). */\nwindow.AUDIO_FILES = '${list.join(' ')}';\n`);
  console.log(`Manifest: ${list.length} files.`);
}
if (flag('manifest')) { writeManifest(); process.exit(0); }

/* ---- --add: import ZIPs exported by the recording studio ---- */
function readZip(file) { // ZIP reader for stored (0) and deflated (8) entries, via the central directory
  const zlib = require('zlib');
  const b = fs.readFileSync(file);
  let e = b.length - 22;
  while (e >= 0 && b.readUInt32LE(e) !== 0x06054b50) e--;
  if (e < 0) throw new Error(file + ' is not a ZIP file');
  const n = b.readUInt16LE(e + 10);
  let p = b.readUInt32LE(e + 16);
  const out = [];
  for (let k = 0; k < n; k++) {
    if (b.readUInt32LE(p) !== 0x02014b50) throw new Error('bad ZIP directory in ' + file);
    const method = b.readUInt16LE(p + 10), csize = b.readUInt32LE(p + 20);
    const nlen = b.readUInt16LE(p + 28), xlen = b.readUInt16LE(p + 30), clen = b.readUInt16LE(p + 32), off = b.readUInt32LE(p + 42);
    const name = b.toString('utf8', p + 46, p + 46 + nlen);
    const lnl = b.readUInt16LE(off + 26), lxl = b.readUInt16LE(off + 28);
    const raw = b.subarray(off + 30 + lnl + lxl, off + 30 + lnl + lxl + csize);
    out.push({ name: path.basename(name), data: method === 8 ? zlib.inflateRawSync(raw) : Buffer.from(raw) });
    p += 46 + nlen + xlen + clen;
  }
  return out;
}
function addZips(files) {
  const { spawnSync } = require('child_process');
  const ffmpeg = spawnSync('ffmpeg', ['-version']).status === 0;
  const ORIG = path.join(ROOT, 'recordings-original');
  fs.mkdirSync(AUDIO, { recursive: true }); fs.mkdirSync(ORIG, { recursive: true });
  if (!ffmpeg) console.log('ffmpeg not found: recordings are copied as they are (no trimming/MP3). Install ffmpeg for smaller files that play on every phone.');
  // trim silence at both ends, cut rumble, even out loudness; mono 48 kbps MP3 (~6 KB per second)
  const filter = 'highpass=f=70,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,areverse,loudnorm=I=-18:TP=-1.5:LRA=11';
  let added = 0;
  const fixes = [];
  for (const z of files) {
    for (const f of readZip(z)) {
      if (f.name === 'text-corrections.tsv') { fixes.push(...f.data.toString('utf8').trim().split('\n').slice(1).filter(Boolean)); continue; }
      if (f.name === 'recordings.tsv') { fs.appendFileSync(path.join(ORIG, 'recordings.tsv'), f.data.toString('utf8').split('\n').slice(1).filter(Boolean).join('\n') + '\n'); continue; }
      const m = f.name.match(/^([0-9a-f]{16})\.(m4a|webm|ogg|mp3|wav)$/);
      if (!m) continue;
      const orig = path.join(ORIG, f.name);
      fs.writeFileSync(orig, f.data);
      // remove older files for this id, so the new recording is the one that plays
      fs.readdirSync(AUDIO).filter((x) => x.startsWith(m[1] + '.')).forEach((x) => fs.unlinkSync(path.join(AUDIO, x)));
      if (ffmpeg) {
        const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', orig, '-af', filter, '-ac', '1', '-ar', '44100', '-b:a', '48k', path.join(AUDIO, m[1] + '.mp3')]);
        if (r.status !== 0) { console.log('  ffmpeg failed for', f.name, '— copied as is'); fs.copyFileSync(orig, path.join(AUDIO, f.name)); }
      } else fs.copyFileSync(orig, path.join(AUDIO, f.name));
      added++;
    }
  }
  console.log(`Added ${added} recordings.`);
  if (fixes.length) {
    fs.appendFileSync(path.join(ROOT, 'data-src', 'text-corrections.tsv'), fixes.join('\n') + '\n');
    console.log(`\nThe speaker flagged ${fixes.length} sentence(s) as written wrongly (saved to data-src/text-corrections.tsv):`);
    fixes.forEach((x) => { const [key, fix] = x.split('\t'); console.log(`  ${key}  →  ${fix || '(no correction typed)'}`); });
  }
  writeManifest();
}
const addAt = args.indexOf('--add');
if (addAt >= 0) {
  const zips = args.slice(addAt + 1).filter((a) => !a.startsWith('--'));
  if (!zips.length) { console.error('Usage: node data-src/build_audio.js --add recordings.zip'); process.exit(1); }
  addZips(zips);
}

/* ---- load the engine and the course data exactly as the browser does ---- */
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const scripts = [...html.matchAll(/<script src="(js\/[^"]+)"/g)].map((m) => m[1]).filter((s) => s === 'js/eg.js' || s.startsWith('js/data/'));
const win = {};
const ctx = vm.createContext({ window: win, document: { dispatchEvent() {}, addEventListener() {} }, CustomEvent: class {}, console, location: { protocol: 'file:' } });
win.window = win;
scripts.forEach((s) => vm.runInContext(fs.readFileSync(path.join(ROOT, s), 'utf8'), ctx, { filename: s }));
const KG = win.KG;
const COURSE = win.COURSE;

// Same learning pass as js/app.js, so word-by-word pronunciations match the site.
(function learn(o, depth) {
  if (depth > 9 || o == null) return;
  if (typeof o === 'string') { if (o.includes('~')) { KG.learnRoman(o); const m = o.match(/\[\[(.+?)\]\]/g); if (m) m.forEach((x) => KG.learnRoman(x.slice(2, -2))); } return; }
  if (Array.isArray(o)) { o.forEach((x) => learn(x, depth + 1)); return; }
  if (typeof o === 'object') Object.keys(o).forEach((k) => { if (k !== 'stage') learn(o[k], depth + 1); });
})([COURSE.stages, win.READERS, win.DROPS, win.ALPHABET, win.READ_DRILL], 0);
((win.LEXICON && win.LEXICON.rows) || []).forEach((r) => { if (r[1]) KG.learnRoman(r[0] + '~' + r[1]); });

/* ---- collect every text a play button can speak ---- */
const texts = new Map(); // key → tts text
const add = (c) => { if (!texts.has(c.key)) texts.set(c.key, c.tts); };
KG.collectSpoken([COURSE.stages, win.READERS, win.DROPS, win.ALPHABET, win.READ_DRILL, win.LINKS, win.LINK_FALSE, win.FUSHA_MAP], add);
KG.collectSpoken(((win.LEXICON && win.LEXICON.rows) || []).map((r) => (r[1] ? r[0] + '~' + r[1] : r[0])), add);
// Arabic written straight into the page code (e.g. the audio test button)
fs.readdirSync(path.join(ROOT, 'js')).filter((f) => f.endsWith('.js')).forEach((f) => {
  const src = fs.readFileSync(path.join(ROOT, 'js', f), 'utf8');
  for (const m of src.matchAll(/data-say="([^"$]+)"/g)) if (KG.hasAr(m[1])) KG.collectSpoken(m[1], add);
});

const voices = opt('voices', flag('azure') || flag('export') ? 'f' : 'f,m').split(',').filter((v) => v === 'f' || v === 'm');
const jobs = [];
for (const v of voices) for (const [key, tts] of texts) jobs.push({ v, key, tts, id: KG.audioId(v, key) });
const chars = [...texts.values()].reduce((n, t) => n + t.length, 0);
if (flag('azure') || flag('dry')) console.log(`${texts.size} texts, ${chars.toLocaleString()} characters per voice (vowel marks included). Azure's free tier covers 500,000 characters a month.`);

/* ---- status: how much is recorded ---- */
if (!flag('azure') && !flag('export') && !flag('dry')) {
  const have = new Set((fs.existsSync(AUDIO) ? fs.readdirSync(AUDIO) : []).map((f) => f.slice(0, 16)));
  const keys = [...texts.keys()];
  const done = keys.filter((k) => voices.some((v) => have.has(KG.audioId(v, k))));
  console.log(`Recorded: ${done.length} of ${keys.length} sentences (${(done.length / keys.length * 100).toFixed(1)}%).`);
  const missing = keys.filter((k) => !voices.some((v) => have.has(KG.audioId(v, k))));
  if (flag('missing')) missing.forEach((k) => console.log('  ' + k));
  else if (missing.length) console.log(`Next up: ${missing.slice(0, 5).join('  ·  ')}${missing.length > 5 ? '  …  (--missing lists all)' : ''}`);
  process.exit(0);
}

if (flag('export')) {
  fs.mkdirSync(AUDIO, { recursive: true });
  const plain = (t) => t.replace(/[\u064B-\u0652\u0670]/g, '');
  const rows = jobs.map((j) => [j.id, j.v, j.key, plain(j.tts), j.tts].map((x) => String(x).replace(/[\t\n]/g, ' ')).join('\t'));
  fs.writeFileSync(path.join(AUDIO, 'jobs.tsv'), 'id\tvoice\tkey\ttext\ttext_with_vowels\n' + rows.join('\n') + '\n');
  console.log(`Wrote audio/jobs.tsv (${jobs.length} rows). Next: run data-src/namaa_tts.py on a GPU (see README).`);
  process.exit(0);
}

if (flag('dry')) {
  [...texts].slice(0, 12).forEach(([k, t]) => console.log('  ', k, k === t ? '' : '→ ' + t));
  process.exit(0);
}

// --azure: generate with Azure (synthesized; off by default on the site)
const T = require('../api/_lib/tts');
if (!T.configured()) { console.error('Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION first (or use --dry).'); process.exit(1); }
fs.mkdirSync(AUDIO, { recursive: true });
const todo = jobs.filter((j) => !fs.existsSync(path.join(AUDIO, j.id + '.mp3')));
console.log(`${jobs.length - todo.length} already exist, generating ${todo.length}…`);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let done = 0, failed = 0;
async function worker() {
  while (todo.length) {
    const j = todo.shift();
    for (let attempt = 0; attempt < 5; attempt++) {
      try {
        const buf = await T.synth(j.tts, j.v, 20000);
        fs.writeFileSync(path.join(AUDIO, j.id + '.mp3'), buf);
        break;
      } catch (e) {
        if (e.status === 401 || e.status === 403) { console.error('Azure rejected the key/region.'); process.exit(1); }
        if (attempt === 4) { failed++; console.error('  failed:', j.key, e.status || e.message); }
        else await sleep(1500 * (attempt + 1) * (e.status === 429 ? 3 : 1));
      }
    }
    if (++done % 100 === 0) console.log(`  ${done}…`);
  }
}
(async () => {
  await Promise.all(Array.from({ length: 4 }, worker));
  const tsv = jobs.map((j) => [j.id, j.v, j.key.replace(/\t/g, ' '), j.tts.replace(/\t/g, ' ')].join('\t'));
  fs.writeFileSync(path.join(AUDIO, 'index.tsv'), 'id\tvoice\tarabic~transcription\tsent_to_azure\n' + tsv.join('\n') + '\n');
  writeManifest();
  console.log(`Done. ${failed} failed.`);
})();
